import { readFile, writeFile } from "node:fs/promises";
import { dirname, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const scriptDirectory = dirname(fileURLToPath(import.meta.url));
const rootDirectory = resolve(scriptDirectory, "..");
const entryFile = resolve(rootDirectory, "src/app.js");
const outputFile = resolve(rootDirectory, "src/app.standalone.js");
const modules = new Map();

function moduleId(file) {
  return relative(rootDirectory, file).replaceAll("\\", "/");
}

function importBindingList(bindings) {
  return bindings
    .split(",")
    .map((binding) => binding.trim())
    .filter(Boolean)
    .map((binding) => {
      const [exported, local = exported] = binding.split(/\s+as\s+/);
      return exported === local ? exported : `${exported}: ${local}`;
    })
    .join(", ");
}

async function compileModule(file) {
  const id = moduleId(file);
  if (modules.has(id)) return id;

  let source = await readFile(file, "utf8");
  const importPattern = /^\s*import\s*\{([\s\S]*?)\}\s*from\s*["']([^"']+)["'];?\s*$/gm;
  const imports = [...source.matchAll(importPattern)];
  for (const match of imports) {
    const dependency = resolve(dirname(file), match[2]);
    await compileModule(dependency);
  }
  source = source.replace(importPattern, (statement, bindings, request) => {
    const dependencyId = moduleId(resolve(dirname(file), request));
    return `const { ${importBindingList(bindings)} } = __require(${JSON.stringify(dependencyId)});`;
  });

  const exports = new Set();
  source = source.replace(/\bexport\s+(async\s+)?function\s+([A-Za-z_$][\w$]*)/g, (statement, asyncKeyword = "", name) => {
    exports.add(name);
    return `${asyncKeyword}function ${name}`;
  });
  source = source.replace(/\bexport\s+(const|let|var|class)\s+([A-Za-z_$][\w$]*)/g, (statement, declaration, name) => {
    exports.add(name);
    return `${declaration} ${name}`;
  });

  const exportLine = exports.size ? `\nObject.assign(exports, { ${[...exports].join(", ")} });` : "";
  modules.set(id, `  ${JSON.stringify(id)}: (module, exports, __require) => {\n${source}\n${exportLine}\n  }`);
  return id;
}

const entryId = await compileModule(entryFile);
const bundle = `/* Generated by scripts/build-standalone.mjs. Do not edit this file directly. */\n(() => {\n  const __modules = {\n${[...modules.values()].join(",\n")}\n  };\n  const __cache = {};\n  const __require = (id) => {\n    if (__cache[id]) return __cache[id].exports;\n    const factory = __modules[id];\n    if (!factory) throw new Error(\`Missing standalone module: \${id}\`);\n    const module = { exports: {} };\n    __cache[id] = module;\n    factory(module, module.exports, __require);\n    return module.exports;\n  };\n  __require(${JSON.stringify(entryId)});\n})();\n`;

await writeFile(outputFile, bundle, "utf8");
console.log(`Built ${moduleId(outputFile)}`);
